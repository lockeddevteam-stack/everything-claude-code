/* Generates 08-build/exercises.js from tests/fixtures/exercise-db.json.
 *   node redesign/tools/gen-exercises.mjs
 * Re-run when the catalogue changes. The output is committed, because the
 * app has to have it without a build step. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rows = JSON.parse(fs.readFileSync(path.join(ROOT, 'tests/fixtures/exercise-db.json'), 'utf8'));
const slim = rows.map((r) => [r.id, r.name, r.group, r.muscle]);

const HEAD = [
  '/* ===================================================================',
  '   The exercise catalogue, as one global.',
  '',
  '   WHY THIS FILE EXISTS. LKCoachActions resolves every exercise id a',
  '   model proposes against the real catalogue, and it had no way to get',
  '   one in a shipped build: the coach fetched a path under tests/, which',
  '   is a fixture and does not deploy, and gave up entirely over file://.',
  '   So in the product every split the coach wrote would have come back',
  '   refused for "the exercise catalogue has not loaded" -- the gate doing',
  '   exactly its job, against a catalogue that was never going to arrive.',
  '',
  '   It ships as rows rather than objects because writing 866 of them out',
  '   long costs several times the bytes for nothing. The shape is',
  '   [id, name, group, muscle]; LKExercises.all() hands back objects.',
  '',
  '   Generated by tools/gen-exercises.mjs. Do not edit by hand.',
  '   =================================================================== */',
  '(function (g) {',
  "  'use strict';",
  '  var ROWS = ' + JSON.stringify(slim) + ';',
  '  var LIST = null;',
  '  g.LKExercises = {',
  '    all: function () {',
  '      if (!LIST) {',
  '        LIST = ROWS.map(function (r) {',
  '          return { id: r[0], name: r[1], group: r[2], muscle: r[3] };',
  '        });',
  '      }',
  '      return LIST;',
  '    },',
  '    count: function () { return ROWS.length; }',
  '  };',
  "})(typeof window !== 'undefined' ? window : this);",
  ''
].join('\n');

fs.writeFileSync(path.join(ROOT, '08-build/exercises.js'), HEAD);
console.log('wrote 08-build/exercises.js — ' + slim.length + ' exercises, ' +
            (HEAD.length / 1024).toFixed(1) + ' KB');
