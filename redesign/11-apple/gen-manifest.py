#!/usr/bin/env python3
"""Regenerate the Feature Freeze Manifest for the redesign build.

    python3 11-apple/gen-manifest.py > /tmp/now.md
    diff 11-apple/FEATURE-MANIFEST.md /tmp/now.md

An empty diff is a clean wave. A skin and motion pass has no business changing
a handler count, a testid, or a storage key, so anything else needs an
explanation before the wave lands.
"""
import re, os, glob, sys

BUILD = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), '08-build')
os.chdir(BUILD)

HANDLER = r'addEventListener\(\s*["\'](\w+)|data-act(?:ion)?="([^"]+)"'
out = []
w = out.append

w("# Feature Freeze Manifest — redesign build")
w("")
w("Generated by parsing `08-build/`, not by reading it, so the freeze check is a")
w("diff rather than a claim. Regenerate with `python3 11-apple/gen-manifest.py`.")
w("")
w("**Rule: nothing here may disappear.** The Apple pass is a skin and motion pass.")
w("A vanished action, a dropped testid, a storage key that stops being written -")
w("any one of those blocks the wave that caused it.")
w("")

files = sorted(glob.glob('*.html'))

w("## Actions per screen")
w("")
w("Every distinct `data-action` / `data-act` value. These are the verbs the")
w("screens dispatch on; losing one is losing a feature.")
w("")
for f in files:
    s = open(f).read()
    acts = sorted(set(re.findall(r'data-act(?:ion)?="([^"]+)"', s)))
    if not acts:
        continue
    w("**%s** — %d" % (f, len(acts)))
    w("")
    w("```")
    for i in range(0, len(acts), 5):
        w("  ".join(a.ljust(22) for a in acts[i:i+5]).rstrip())
    w("```")
    w("")

w("## Test ids per screen")
w("")
w("The selectors every test and every audit script addresses.")
w("")
w("| Screen | testids |")
w("|---|---|")
for f in files:
    s = open(f).read()
    w("| `%s` | %d |" % (f, len(set(re.findall(r'data-testid="([^"]+)"', s)))))
w("")

allkeys = set()
for f in files + ['theme.js', 'app.js', 'bodymap.js']:
    s = open(f).read()
    allkeys |= set(re.findall(r'localStorage\.(?:get|set|remove)Item\(\s*["\']([A-Za-z0-9_]+)', s))
w("## Storage keys — %d" % len(allkeys))
w("")
w("```")
ks = sorted(allkeys)
for i in range(0, len(ks), 4):
    w("  ".join(k.ljust(24) for k in ks[i:i+4]).rstrip())
w("```")
w("")

w("## Per-screen totals")
w("")
w("| Screen | Lines | Listeners | Actions | Buttons | Inputs | testids |")
w("|---|---|---|---|---|---|---|")
t = [0]*6
for f in files:
    s = open(f).read()
    row = [s.count('\n'),
           len(re.findall(r'addEventListener\(', s)),
           len(set(re.findall(r'data-act(?:ion)?="([^"]+)"', s))),
           len(re.findall(r'<button|createElement\("button"', s)),
           len(re.findall(r'<input|<textarea|<select', s)),
           len(set(re.findall(r'data-testid="([^"]+)"', s)))]
    for i, v in enumerate(row):
        t[i] += v
    w("| `%s` | %s |" % (f, " | ".join(str(v) for v in row)))
w("| **total** | %s |" % " | ".join("**%d**" % v for v in t))
print("\n".join(out))
