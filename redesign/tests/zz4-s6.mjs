import {open,DEMO,T,ids as IDS} from './zz4-lib.mjs';
const {b,p,errs}=await open(DEMO+'#/profile/settings');
await p.waitForTimeout(1500);
await p.click('[data-testid="row-body"]'); await p.waitForTimeout(600);
await p.fill('[data-testid="field-age"]','31');
await p.fill('[data-testid="field-height"]','172');
await p.fill('[data-testid="field-weight"]','70.5');
await p.click('[data-testid="save-body"]'); await p.waitForTimeout(800);
console.log('body row:',T(await p.locator('[data-testid="row-body"]').innerText()));
console.log('stored:',await p.evaluate(()=>localStorage.getItem('lk_profile')));
await p.reload(); await p.waitForTimeout(1600);
console.log('AFTER RELOAD body row:',T(await p.locator('[data-testid="row-body"]').innerText()));
// invalid values
await p.click('[data-testid="row-body"]'); await p.waitForTimeout(600);
await p.fill('[data-testid="field-age"]','999'); await p.fill('[data-testid="field-weight"]','0');
await p.click('[data-testid="save-body"]'); await p.waitForTimeout(700);
const sh=p.locator('[data-testid="sheet-body"]');
console.log('\nafter invalid save, sheet open:',await sh.count(),'|',await sh.count()?T(await sh.innerText()).slice(0,400):'');
console.log('body row now:',T(await p.locator('[data-testid="row-body"]').innerText()));
console.log('stored:',await p.evaluate(()=>localStorage.getItem('lk_profile')));
console.log('ERRS',errs);
await b.close();
