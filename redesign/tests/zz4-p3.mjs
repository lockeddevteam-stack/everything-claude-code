import {open,DEMO,T,ids as IDS} from './zz4-lib.mjs';
const {b,p,errs}=await open(DEMO+'#/coach');
await p.waitForTimeout(800);
const PV=async()=>T(await p.locator('[data-testid="view-plan"]').innerText()).slice(0,700);
await p.click('[data-testid="seg-plan"]'); await p.waitForTimeout(500);
await p.click('[data-testid="plan-bind-open"]'); await p.waitForTimeout(400);
await p.click('[data-testid="bind-split-1"]'); await p.waitForTimeout(600);
await p.click('[data-testid="plan-delete"]'); await p.waitForTimeout(500);
await p.click('[data-testid="delete-confirm"]'); await p.waitForTimeout(700);
console.log('AFTER CONFIRM:',await PV());
console.log('toast:',T(await p.locator('[data-testid="toast"]').innerText()));
console.log('storage plan:',await p.evaluate(()=>localStorage.getItem('lk_coachPlan')));
await p.click('[data-testid="toast-action"]'); await p.waitForTimeout(700);
console.log('\nAFTER UNDO:',await PV());
console.log('storage plan after undo:',(await p.evaluate(()=>localStorage.getItem('lk_coachPlan')))?.slice(0,120));
await p.reload(); await p.waitForTimeout(1200); await p.click('[data-testid="seg-plan"]'); await p.waitForTimeout(500);
console.log('\nAFTER RELOAD:',await PV());
// now delete again and reload without undo
await p.click('[data-testid="plan-delete"]'); await p.waitForTimeout(400);
await p.click('[data-testid="delete-confirm"]'); await p.waitForTimeout(600);
await p.reload(); await p.waitForTimeout(1200); await p.click('[data-testid="seg-plan"]'); await p.waitForTimeout(500);
console.log('\nDELETED + RELOAD:',await PV());
console.log('ERRS',errs);
await b.close();
