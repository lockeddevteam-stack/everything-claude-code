import {open,DEMO,T,ids as IDS} from './zz4-lib.mjs';
const {b,p,errs}=await open(DEMO+'#/profile/settings');
await p.waitForTimeout(1500);
let file=null;
p.on('download',async d=>{file='/tmp/claude-0/zz4b.json';await d.saveAs(file)});
await p.click('[data-testid="row-body"]'); await p.waitForTimeout(400);
await p.fill('[data-testid="field-weight"]','80'); await p.click('[data-testid="save-body"]'); await p.waitForTimeout(500);
await p.click('[data-testid="row-export"]'); await p.waitForTimeout(2000);
await p.click('[data-testid="row-body"]'); await p.waitForTimeout(400);
await p.fill('[data-testid="field-weight"]','55'); await p.click('[data-testid="save-body"]'); await p.waitForTimeout(500);
await p.click('[data-testid="row-restore"]'); await p.waitForTimeout(600);
console.log('dialog:',T(await p.locator('[data-testid="dialog-restore"]').innerText()).slice(0,500));
const [fc]=await Promise.all([p.waitForEvent('filechooser').catch(()=>null),p.click('[data-testid="confirm-restore"]')]);
await p.waitForTimeout(800);
if(fc){console.log('file chooser opened'); await fc.setFiles(file); await p.waitForTimeout(1500);}
else console.log('no file chooser; ids:',(await IDS(p)).filter(x=>/restore|toast|dialog/.test(x)).join(','));
const t=p.locator('[data-testid="toast"]'); if(await t.count())console.log('toast:',T(await t.innerText()));
console.log('body:',T(await p.locator('[data-testid="row-body"]').innerText()));
await p.reload(); await p.waitForTimeout(1600);
console.log('AFTER RELOAD body:',T(await p.locator('[data-testid="row-body"]').innerText()));
console.log('ERRS',errs);
await b.close();
