/* Sample Apple's spring presets into CSS linear() timing functions.

   The maths is the corrected form from the spec, section 4.2:

     mass      = 1
     stiffness = (2pi / duration)^2
     damping   = ((1 - bounce) * 4pi) / duration      for bounce >= 0
     dampingRatio = 1 - bounce

   A CSS linear() runs on the compositor, so a sampled spring costs the same
   as an ease and cannot jank. What it cannot do is pick up a gesture's
   velocity, which is what the rAF solver in app.js is for. Anything with a
   known start and end uses these; anything a finger threw uses that. */

function spring(duration, bounce) {
  const mass = 1;
  const stiffness = Math.pow((2 * Math.PI) / duration, 2);
  const damping = bounce >= 0
    ? ((1 - bounce) * 4 * Math.PI) / duration
    : (4 * Math.PI) / (duration * (1 + bounce));
  return { mass, stiffness, damping, zeta: bounce >= 0 ? 1 - bounce : 1 / (1 + bounce) };
}

/* Displacement of a unit step, solved in closed form for the under- and
   over-damped cases and by the critical form when zeta is 1. */
function value(t, { stiffness, damping, mass }) {
  const wn = Math.sqrt(stiffness / mass);
  const zeta = damping / (2 * Math.sqrt(stiffness * mass));
  if (zeta < 1) {
    const wd = wn * Math.sqrt(1 - zeta * zeta);
    return 1 - Math.exp(-zeta * wn * t) * (Math.cos(wd * t) + (zeta * wn / wd) * Math.sin(wd * t));
  }
  if (Math.abs(zeta - 1) < 1e-6) return 1 - Math.exp(-wn * t) * (1 + wn * t);
  const a = wn * (zeta + Math.sqrt(zeta * zeta - 1));
  const b = wn * (zeta - Math.sqrt(zeta * zeta - 1));
  return 1 - (a * Math.exp(-b * t) - b * Math.exp(-a * t)) / (a - b);
}

function linearFn(duration, bounce, samples = 34) {
  const s = spring(duration, bounce);
  const pts = [];
  for (let i = 0; i <= samples; i++) {
    const t = (i / samples) * duration;
    pts.push(Math.round(value(t, s) * 10000) / 10000);
  }
  pts[pts.length - 1] = 1;
  return 'linear(' + pts.join(', ') + ')';
}

const PRESETS = [
  ['smooth', 0.5, 0.0, 'layout shifts and opacity, where overshoot reads as sloppy'],
  ['snappy', 0.5, 0.15, 'the default: taps, toggles, sheet snaps, tab switches'],
  ['bouncy', 0.5, 0.30, 'the wobble: card expansion, glass press, celebrations'],
];

console.log('/* Generated by tests/gen-springs.mjs. Do not hand-edit.');
console.log('   Each curve is a real spring solved from duration and bounce, sampled to');
console.log('   a linear() so it runs on the compositor. Regenerate rather than tune. */');
for (const [name, dur, bounce, why] of PRESETS) {
  const s = spring(dur, bounce);
  console.log(`  /* ${name}: ${dur}s, bounce ${bounce} — ${why}`);
  console.log(`     stiffness ${s.stiffness.toFixed(1)}, damping ${s.damping.toFixed(1)}, zeta ${s.zeta.toFixed(3)} */`);
  console.log(`  --spring-${name}: ${linearFn(dur, bounce)};`);
}
/* Peak overshoot, so the wobble can be asserted rather than trusted. */
for (const [name, dur, bounce] of PRESETS) {
  const s = spring(dur, bounce);
  let peak = 0;
  for (let i = 0; i <= 400; i++) peak = Math.max(peak, value((i / 400) * dur * 2, s));
  console.error(`${name}: peak ${(peak * 100).toFixed(1)}% of target`);
}
