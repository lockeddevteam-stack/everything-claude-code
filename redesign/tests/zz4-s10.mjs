import {open,DEMO,T,ids as IDS} from './zz4-lib.mjs';
const {b,p,errs}=await open(DEMO+'#/profile/settings');
await p.waitForTimeout(1500);
await p.click('[data-testid="row-body"]'); await p.waitForTimeout(400);
await p.fill('[data-testid="field-weight"]','99'); await p.click('[data-testid="save-body"]'); await p.waitForTimeout(500);
await p.click('[data-testid="row-reset"]'); await p.waitForTimeout(600);
console.log('dialog:',T(await p.locator('[data-testid="dialog-reset"]').innerText()).slice(0,400));
await p.click('[data-testid="confirm-reset"]'); await p.waitForTimeout(1500);
console.log('toast:',await p.locator('[data-testid="toast"]').count()?T(await p.locator('[data-testid="toast"]').innerText()):'(none)');
console.log('body:',T(await p.locator('[data-testid="row-body"]').innerText()));
console.log('storage keys:',await p.evaluate(()=>Object.keys(localStorage)));
await p.goto(DEMO+'#/profile'); await p.waitForTimeout(1200);
console.log('PROFILE:',T(await p.locator('[data-testid="screen-profile"]').first().innerText()).slice(0,400));
await p.goto(DEMO+'#/home'); await p.waitForTimeout(1400);
console.log('HOME:',T(await p.locator('body').innerText()).replace(/^SCREENS \| /,'').slice(0,500));
await p.reload(); await p.waitForTimeout(1800);
console.log('\nAFTER RELOAD HOME:',T(await p.locator('body').innerText()).slice(0,500));
console.log('ERRS',errs);
await b.close();
