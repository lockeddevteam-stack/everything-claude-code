import {open,DEMO,T,ids as IDS,CYCLEON} from './zz4-lib.mjs';
const {b,p,errs}=await open(DEMO+'#/home/cycle',CYCLEON);
await p.waitForTimeout(1400);
const cells=async()=>p.$$eval('[data-testid^="cyc-2026"]',ns=>ns.map(n=>n.dataset.testid.slice(4)+'|'+(n.getAttribute('aria-label')||'')+'|'+n.className));
console.log('NORMAL CELLS:'); (await cells()).slice(-14).forEach(c=>console.log('  ',c));
console.log('\nring html:',(await p.locator('[data-testid="cycle-ring"]').innerHTML()).replace(/\s+/g,' ').slice(0,900));
await p.click('[data-testid="cycle-settings"]'); await p.waitForTimeout(500);
console.log('\ncs-discreet HTML before:',(await p.locator('[data-testid="cs-discreet"]').innerHTML()).replace(/\s+/g,' ').slice(0,400));
await p.click('[data-testid="cs-discreet"]'); await p.waitForTimeout(400);
console.log('cs-discreet HTML after :',(await p.locator('[data-testid="cs-discreet"]').innerHTML()).replace(/\s+/g,' ').slice(0,400));
await p.click('[data-testid="cs-save"]'); await p.waitForTimeout(700);
console.log('\nDISCREET CELLS:'); (await cells()).slice(-14).forEach(c=>console.log('  ',c));
console.log('\nring html:',(await p.locator('[data-testid="cycle-ring"]').innerHTML()).replace(/\s+/g,' ').slice(0,900));
await p.click('[data-testid="cycle-settings"]'); await p.waitForTimeout(500);
console.log('\ncs-discreet reopened:',(await p.locator('[data-testid="cs-discreet"]').innerHTML()).replace(/\s+/g,' ').slice(0,400));
